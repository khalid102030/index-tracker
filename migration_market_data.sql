-- كل صف = سهم واحد في لقطة معيّنة
-- snapshot_batch = معرّف اللقطة (التاريخ_الوقت، مثل 2026-08-09_15-15)
-- data = كل أعمدة المؤشرات كـ JSONB (نفس أعمدة الشيت بالضبط)

CREATE TABLE IF NOT EXISTS idx_market_data (
    id             BIGSERIAL PRIMARY KEY,
    snapshot_batch TEXT NOT NULL,        -- معرّف اللقطة (التاريخ_الوقت)
    symbol         TEXT,                 -- الرمز (للفهرسة)
    data           JSONB NOT NULL,       -- كل أعمدة المؤشرات
    created_at     TIMESTAMPTZ DEFAULT NOW()
);

-- فهارس للسرعة
CREATE INDEX IF NOT EXISTS idx_md_batch ON idx_market_data(snapshot_batch DESC);
CREATE INDEX IF NOT EXISTS idx_md_symbol ON idx_market_data(symbol);

-- ═══════════════════════════════════════════════════════════════
--  ملاحظة حول تعبئة البيانات:
